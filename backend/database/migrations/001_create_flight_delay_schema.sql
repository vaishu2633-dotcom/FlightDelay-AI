-- 1. Ensure required extensions exist
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ==============================================================================
-- Table 1: user_profiles
-- Linked to Supabase auth.users for authenticated researcher/passenger profiles
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.user_profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ==============================================================================
-- Table 2: dataset_metadata
-- Stores historical BTS flight dataset tracking and class imbalance statistics
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.dataset_metadata (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    dataset_name TEXT NOT NULL,
    source TEXT NOT NULL,
    total_records BIGINT NOT NULL CHECK (total_records >= 0),
    start_date DATE,
    end_date DATE,
    delayed_count BIGINT NOT NULL DEFAULT 0 CHECK (delayed_count >= 0),
    on_time_count BIGINT NOT NULL DEFAULT 0 CHECK (on_time_count >= 0),
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ==============================================================================
-- Table 3: model_versions
-- Tracks ML model artifacts, training timestamps, and active status
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.model_versions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    model_name TEXT NOT NULL,
    version TEXT NOT NULL UNIQUE,
    dataset_id UUID REFERENCES public.dataset_metadata(id) ON DELETE SET NULL,
    trained_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived', 'deprecated', 'training'))
);

-- ==============================================================================
-- Table 4: model_metrics
-- Stores empirical validation metrics (accuracy, precision, recall, PR-AUC, ROC-AUC)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.model_metrics (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    model_version_id UUID NOT NULL REFERENCES public.model_versions(id) ON DELETE CASCADE,
    resampling_method TEXT NOT NULL,
    accuracy NUMERIC(6, 4) NOT NULL CHECK (accuracy >= 0 AND accuracy <= 1),
    precision NUMERIC(6, 4) NOT NULL CHECK (precision >= 0 AND precision <= 1),
    recall NUMERIC(6, 4) NOT NULL CHECK (recall >= 0 AND recall <= 1),
    f1_score NUMERIC(6, 4) NOT NULL CHECK (f1_score >= 0 AND f1_score <= 1),
    pr_auc NUMERIC(6, 4) NOT NULL CHECK (pr_auc >= 0 AND pr_auc <= 1),
    roc_auc NUMERIC(6, 4) NOT NULL CHECK (roc_auc >= 0 AND roc_auc <= 1),
    confusion_matrix JSONB,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ==============================================================================
-- Table 5: prediction_history
-- Stores genuine inferences generated by the validated ML pipeline
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.prediction_history (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES public.user_profiles(id) ON DELETE SET NULL,
    airline VARCHAR(10) NOT NULL,
    origin VARCHAR(10) NOT NULL,
    destination VARCHAR(10) NOT NULL,
    flight_date DATE NOT NULL,
    scheduled_departure_time VARCHAR(10) NOT NULL,
    predicted_delay BOOLEAN NOT NULL,
    delay_probability NUMERIC(6, 4) NOT NULL CHECK (delay_probability >= 0 AND delay_probability <= 1),
    model_version_id UUID REFERENCES public.model_versions(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ==============================================================================
-- Indexes for Performance
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_prediction_history_user_id ON public.prediction_history(user_id);
CREATE INDEX IF NOT EXISTS idx_prediction_history_created_at ON public.prediction_history(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_prediction_history_filters ON public.prediction_history(flight_date, airline, origin, destination);
CREATE INDEX IF NOT EXISTS idx_model_versions_version ON public.model_versions(version);
CREATE INDEX IF NOT EXISTS idx_model_metrics_version_id ON public.model_metrics(model_version_id);
CREATE INDEX IF NOT EXISTS idx_dataset_metadata_dates ON public.dataset_metadata(start_date, end_date);

