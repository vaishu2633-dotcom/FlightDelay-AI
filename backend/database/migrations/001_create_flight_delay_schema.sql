-- Allows clients to view validated model versions, benchmarks, and dataset metadata
DROP POLICY IF EXISTS "Public read access for model versions" ON public.model_versions;
CREATE POLICY "Public read access for model versions"
    ON public.model_versions
    FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Public read access for model metrics" ON public.model_metrics;
CREATE POLICY "Public read access for model metrics"
    ON public.model_metrics
    FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Public read access for dataset metadata" ON public.dataset_metadata;
CREATE POLICY "Public read access for dataset metadata"
    ON public.dataset_metadata
    FOR SELECT
    USING (true);

