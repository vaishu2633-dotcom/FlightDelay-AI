ALTER TABLE public.user_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dataset_metadata ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.model_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.model_metrics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.prediction_history ENABLE ROW LEVEL SECURITY;

-- 2. user_profiles Policies
-- Users can only read and update their own profile record
DROP POLICY IF EXISTS "Users can read own profile" ON public.user_profiles;
CREATE POLICY "Users can read own profile"
    ON public.user_profiles
    FOR SELECT
    USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update own profile" ON public.user_profiles;
CREATE POLICY "Users can update own profile"
    ON public.user_profiles
    FOR UPDATE
    USING (auth.uid() = id);

-- 3. prediction_history Policies
-- Authenticated users can only read their own predictions
DROP POLICY IF EXISTS "Users can view own prediction history" ON public.prediction_history;
CREATE POLICY "Users can view own prediction history"
    ON public.prediction_history
    FOR SELECT
    USING (auth.uid() = user_id);

-- Restrict all public and anonymous inserts directly to PostgreSQL
-- Privileged writes are handled exclusively through server-side backend endpoints
DROP POLICY IF EXISTS "Disallow public inserts to prediction history" ON public.prediction_history;
CREATE POLICY "Disallow public inserts to prediction history"
    ON public.prediction_history
    FOR INSERT
    WITH CHECK (false);

